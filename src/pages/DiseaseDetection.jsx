import { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { motion, AnimatePresence } from 'framer-motion';
import { ScanLine, Bot, RotateCcw, Leaf, AlertCircle, AlertTriangle } from 'lucide-react';
import { useTheme } from '../context/ThemeContext';
import { useApi } from '../hooks/useApi';
import { predictDisease } from '../api/diseaseApi';
import ImageUploader from '../components/ImageUploader';
import LoadingSpinner from '../components/LoadingSpinner';
import ErrorMessage from '../components/ErrorMessage';
import ConfidenceChart from '../components/ConfidenceChart';

export default function DiseaseDetection() {
  const { isDark } = useTheme();
  const navigate = useNavigate();
  const [selectedFile, setSelectedFile] = useState(null);
  const [imagePreviewUrl, setImagePreviewUrl] = useState(null);
  const { data: result, loading, error, execute, reset } = useApi(predictDisease);

  const handleFileSelect = (file) => {
    setSelectedFile(file);
    setImagePreviewUrl(file ? URL.createObjectURL(file) : null);
    reset();
  };

  const handleAnalyze = async () => {
    if (!selectedFile) return;
    try { await execute(selectedFile); } catch (_) {}
  };

  const handleReset = () => {
    setSelectedFile(null);
    setImagePreviewUrl(null);
    reset();
  };

  const handleAskAI = () => {
    if (!result?.prediction) return;
    const params = new URLSearchParams({
      crop: result.prediction.crop || '',
      disease: result.prediction.label || '',
      confidence: result.prediction.confidence?.toString() || '',
    });
    navigate(`/assistant?${params.toString()}`);
  };

  const prediction = result?.prediction;
  const topPredictions = result?.top_predictions || [];
  const lowConfidence = result && !prediction;

  return (
    <div className="min-h-screen pt-24 pb-16">
      <div className="max-w-4xl mx-auto px-4 sm:px-6 lg:px-8">

        {/* Header */}
        <motion.div initial={{ opacity: 0, y: 15 }} animate={{ opacity: 1, y: 0 }} className="mb-8">
          <div className="flex items-center gap-3 mb-3">
            <div className="w-10 h-10 rounded-xl bg-gradient-to-br from-cyan-500 to-blue-600 flex items-center justify-center">
              <ScanLine className="w-5 h-5 text-white" />
            </div>
            <h1 className={`text-3xl font-bold ${isDark ? 'text-white' : 'text-surface-900'}`}>
              Leaf Disease Detection
            </h1>
          </div>
          <p className={`text-base max-w-2xl ${isDark ? 'text-surface-400' : 'text-surface-600'}`}>
            Upload a crop leaf image to classify it using the pretrained MobileNetV2 model.
          </p>
        </motion.div>

        <AnimatePresence mode="wait">
          {!result ? (
            <motion.div key="upload" initial={{ opacity: 0 }} animate={{ opacity: 1 }} exit={{ opacity: 0 }}>
              <div className={`rounded-2xl border p-6 sm:p-8 mb-6 ${isDark ? 'border-white/5 bg-white/[0.02]' : 'border-surface-200 bg-white'}`}>
                <ImageUploader onFileSelect={handleFileSelect} disabled={loading} />

                {error && <div className="mt-6"><ErrorMessage message={error} onRetry={handleAnalyze} /></div>}
                {loading && <div className="mt-6"><LoadingSpinner message="Analyzing leaf image..." /></div>}

                {selectedFile && !loading && (
                  <motion.div initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} className="mt-6 flex justify-center">
                    <button
                      onClick={handleAnalyze}
                      className="inline-flex items-center gap-2 px-8 py-3 rounded-xl bg-gradient-to-r from-cyan-500 to-blue-600 text-white font-semibold text-sm
                        hover:from-cyan-600 hover:to-blue-700 shadow-lg shadow-cyan-500/25 transition-all duration-200"
                    >
                      <ScanLine className="w-4 h-4" />
                      Analyze Image
                    </button>
                  </motion.div>
                )}
              </div>

              <div className={`rounded-2xl border p-5 ${isDark ? 'border-white/5 bg-white/[0.02]' : 'border-surface-200 bg-surface-50'}`}>
                <div className="flex items-start gap-3">
                  <AlertCircle className={`w-5 h-5 mt-0.5 flex-shrink-0 ${isDark ? 'text-surface-500' : 'text-surface-400'}`} />
                  <div>
                    <p className={`text-sm font-medium mb-1 ${isDark ? 'text-surface-300' : 'text-surface-700'}`}>AI-Assisted Analysis</p>
                    <p className={`text-xs leading-relaxed ${isDark ? 'text-surface-500' : 'text-surface-500'}`}>
                      Predictions are generated by a pretrained MobileNetV2 model (38 plant disease classes).
                      This is not a replacement for expert agricultural consultation.
                    </p>
                  </div>
                </div>
              </div>
            </motion.div>

          ) : (
            <motion.div key="result" initial={{ opacity: 0, y: 20 }} animate={{ opacity: 1, y: 0 }} exit={{ opacity: 0 }}>
              <div className={`rounded-2xl border overflow-hidden ${isDark ? 'border-white/5 bg-white/[0.02]' : 'border-surface-200 bg-white'}`}>

                {/* Image preview */}
                {imagePreviewUrl && (
                  <div className={`p-6 border-b ${isDark ? 'border-white/5 bg-white/[0.01]' : 'border-surface-100 bg-surface-50'}`}>
                    <img src={imagePreviewUrl} alt="Analyzed leaf" className="max-h-64 mx-auto rounded-xl object-contain" />
                  </div>
                )}

                <div className="p-6 sm:p-8">
                  {/* Low confidence warning */}
                  {lowConfidence && (
                    <div className={`flex items-start gap-3 p-4 rounded-xl mb-6 ${isDark ? 'bg-yellow-500/10 border border-yellow-500/20' : 'bg-yellow-50 border border-yellow-200'}`}>
                      <AlertTriangle className="w-5 h-5 text-yellow-500 flex-shrink-0 mt-0.5" />
                      <p className={`text-sm ${isDark ? 'text-yellow-300' : 'text-yellow-800'}`}>{result.message}</p>
                    </div>
                  )}

                  {/* Main prediction */}
                  {prediction && (
                    <>
                      <div className="text-center mb-6">
                        <div className={`inline-flex items-center gap-2 px-3 py-1 rounded-full text-xs font-medium mb-3 ${isDark ? 'bg-agri-500/10 text-agri-400' : 'bg-agri-50 text-agri-700'}`}>
                          <Leaf className="w-3.5 h-3.5" />
                          {prediction.crop}
                        </div>
                        <h2 className={`text-2xl sm:text-3xl font-bold mb-2 ${isDark ? 'text-white' : 'text-surface-900'}`}>
                          {prediction.disease}
                        </h2>
                      </div>

                      <div className="max-w-md mx-auto mb-6">
                        <ConfidenceChart confidence={prediction.confidence} />
                      </div>

                      <div className={`grid grid-cols-2 sm:grid-cols-3 gap-3 p-4 rounded-xl mb-6 ${isDark ? 'bg-white/[0.03]' : 'bg-surface-50'}`}>
                        <div>
                          <p className={`text-xs ${isDark ? 'text-surface-500' : 'text-surface-400'}`}>Crop</p>
                          <p className={`text-sm font-medium ${isDark ? 'text-surface-200' : 'text-surface-800'}`}>{prediction.crop}</p>
                        </div>
                        <div>
                          <p className={`text-xs ${isDark ? 'text-surface-500' : 'text-surface-400'}`}>Disease</p>
                          <p className={`text-sm font-medium ${isDark ? 'text-surface-200' : 'text-surface-800'}`}>{prediction.disease}</p>
                        </div>
                        <div>
                          <p className={`text-xs ${isDark ? 'text-surface-500' : 'text-surface-400'}`}>Confidence</p>
                          <p className={`text-sm font-medium ${isDark ? 'text-surface-200' : 'text-surface-800'}`}>{prediction.confidence}%</p>
                        </div>
                      </div>
                    </>
                  )}

                  {/* Top 3 predictions */}
                  {topPredictions.length > 0 && (
                    <div>
                      <p className={`text-xs font-semibold uppercase tracking-wider mb-3 ${isDark ? 'text-surface-500' : 'text-surface-400'}`}>
                        Top Predictions
                      </p>
                      <div className="space-y-2">
                        {topPredictions.map((p, i) => (
                          <div key={i} className={`flex items-center justify-between px-4 py-3 rounded-xl ${isDark ? 'bg-white/[0.03]' : 'bg-surface-50'}`}>
                            <div className="flex items-center gap-3">
                              <span className={`text-xs font-bold w-5 text-center ${i === 0 ? 'text-cyan-500' : isDark ? 'text-surface-500' : 'text-surface-400'}`}>
                                #{i + 1}
                              </span>
                              <div>
                                <p className={`text-sm font-medium ${isDark ? 'text-surface-200' : 'text-surface-800'}`}>{p.disease}</p>
                                <p className={`text-xs ${isDark ? 'text-surface-500' : 'text-surface-400'}`}>{p.crop}</p>
                              </div>
                            </div>
                            <span className={`text-sm font-semibold ${i === 0 ? 'text-cyan-500' : isDark ? 'text-surface-400' : 'text-surface-600'}`}>
                              {p.confidence}%
                            </span>
                          </div>
                        ))}
                      </div>
                    </div>
                  )}
                </div>

                {/* Actions */}
                <div className={`px-6 sm:px-8 py-5 border-t flex flex-wrap gap-3 justify-center ${isDark ? 'border-white/5' : 'border-surface-100'}`}>
                  {prediction && (
                    <button
                      onClick={handleAskAI}
                      className="inline-flex items-center gap-2 px-6 py-2.5 rounded-xl bg-gradient-to-r from-violet-500 to-purple-600 text-white text-sm font-semibold
                        hover:from-violet-600 hover:to-purple-700 shadow-lg shadow-violet-500/20 transition-all"
                    >
                      <Bot className="w-4 h-4" />
                      Ask AI About This Disease
                    </button>
                  )}
                  <button
                    onClick={handleReset}
                    className={`inline-flex items-center gap-2 px-6 py-2.5 rounded-xl border text-sm font-semibold transition-all ${isDark
                      ? 'border-white/10 text-white hover:bg-white/5'
                      : 'border-surface-300 text-surface-700 hover:bg-surface-50'
                    }`}
                  >
                    <RotateCcw className="w-4 h-4" />
                    Analyze Another Image
                  </button>
                </div>
              </div>
            </motion.div>
          )}
        </AnimatePresence>
      </div>
    </div>
  );
}
